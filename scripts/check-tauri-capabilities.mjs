import assert from "node:assert/strict";
import { readdir, readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    "..",
);
const appRoot = path.join(repoRoot, "apps", "lorepia");
const tauriRoot = path.join(appRoot, "src-tauri");
const capabilityRoot = path.join(tauriRoot, "capabilities");
const permissionRoot = path.join(tauriRoot, "permissions", "autogenerated");
const commandPattern = /^[a-z][a-z0-9]*(?:_[a-z0-9]+)*$/;
const permissionPattern = /^allow-[a-z0-9]+(?:-[a-z0-9]+)*$/;

const relative = (file) => path.relative(repoRoot, file);

const assertUnique = (values, label) => {
    const duplicates = [
        ...new Set(values.filter((value, index) => values.indexOf(value) !== index)),
    ].sort();
    assert.deepEqual(duplicates, [], `${label} contains duplicate entries`);
};

const assertCommandList = (commands, label) => {
    assert.ok(Array.isArray(commands), `${label} must be an array`);
    assert.ok(commands.length > 0, `${label} must not be empty`);
    for (const command of commands) {
        assert.equal(typeof command, "string", `${label} contains a non-string command`);
        assert.match(command, commandPattern, `${label} contains a malformed command`);
    }
    assertUnique(commands, label);
};

const assertExactCommandSurface = (expected, actual, label) => {
    assertCommandList(actual, label);
    assert.deepEqual(
        [...actual].sort(),
        [...expected].sort(),
        `${label} drifted from the Tauri invoke handler`,
    );
};

const permissionForCommand = (command) => `allow-${command.replaceAll("_", "-")}`;

const commandForPermission = (permission, label) => {
    assert.equal(typeof permission, "string", `${label} contains a non-string permission`);
    assert.match(permission, permissionPattern, `${label} contains a malformed permission`);
    assert.equal(
        /^allow-(?:fs|shell)(?:-|$)/.test(permission),
        false,
        `${label} contains a filesystem or shell permission`,
    );

    const command = permission.slice("allow-".length).replaceAll("-", "_");
    assert.match(command, commandPattern, `${label} contains a malformed command permission`);
    assert.equal(
        permissionForCommand(command),
        permission,
        `${label} contains a non-canonical command permission`,
    );
    return command;
};

const extractSingleBlock = (source, pattern, label) => {
    const matches = [...source.matchAll(pattern)];
    assert.equal(matches.length, 1, `${label} must appear exactly once`);
    return matches[0][1];
};

const parseStrictList = (body, entryPattern, label) => {
    const values = [];
    let offset = 0;

    while (offset < body.length) {
        const whitespace = body.slice(offset).match(/^\s*/)[0];
        offset += whitespace.length;
        if (offset === body.length) {
            break;
        }

        const match = body.slice(offset).match(entryPattern);
        assert.ok(
            match,
            `${label} contains malformed or unsupported syntax near ${JSON.stringify(
                body.slice(offset, offset + 80),
            )}`,
        );
        values.push(match[1]);
        offset += match[0].length;
    }

    assertCommandList(values, label);
    return values;
};

const parseInvokeHandler = (source) => {
    const body = extractSingleBlock(
        source,
        /\.invoke_handler\(\s*tauri::generate_handler!\s*\[([\s\S]*?)\]\s*\)/g,
        "Tauri invoke handler",
    );
    return parseStrictList(
        body,
        /^(?:[A-Za-z_][A-Za-z0-9_]*::)+([a-z][a-z0-9]*(?:_[a-z0-9]+)*)\s*,/,
        "Tauri invoke handler",
    );
};

const parseBuildCommands = (source) => {
    const body = extractSingleBlock(
        source,
        /\bconst\s+APP_COMMANDS\s*:\s*&\[\s*&str\s*\]\s*=\s*&\[([\s\S]*?)\];/g,
        "build.rs APP_COMMANDS",
    );
    return parseStrictList(
        body,
        /^"([a-z][a-z0-9]*(?:_[a-z0-9]+)*)"\s*,/,
        "build.rs APP_COMMANDS",
    );
};

const commandRegistryKey = (command) =>
    command.replaceAll(/_([a-z0-9])/g, (_, character) => character.toUpperCase());

const parseFrontendCommandRegistry = (source) => {
    const body = extractSingleBlock(
        source,
        /\bexport\s+const\s+LOREPIA_COMMANDS\s*=\s*\{([\s\S]*?)\}\s+as\s+const\s*;/g,
        "frontend LOREPIA_COMMANDS",
    );
    const keys = [];
    const commands = [];
    let offset = 0;

    while (offset < body.length) {
        const whitespace = body.slice(offset).match(/^\s*/)[0];
        offset += whitespace.length;
        if (offset === body.length) {
            break;
        }

        const match = body
            .slice(offset)
            .match(
                /^([A-Za-z_$][A-Za-z0-9_$]*)\s*:\s*'([a-z][a-z0-9]*(?:_[a-z0-9]+)*)'\s*,/,
            );
        assert.ok(
            match,
            `frontend LOREPIA_COMMANDS contains malformed or unsupported syntax near ${JSON.stringify(
                body.slice(offset, offset + 80),
            )}`,
        );
        const [, key, command] = match;
        assert.equal(
            key,
            commandRegistryKey(command),
            `frontend LOREPIA_COMMANDS key ${key} does not canonically name ${command}`,
        );
        keys.push(key);
        commands.push(command);
        offset += match[0].length;
    }

    assertUnique(keys, "frontend LOREPIA_COMMANDS keys");
    assertCommandList(commands, "frontend LOREPIA_COMMANDS values");
    return commands;
};

const assertJsonObjectKeysUnique = (source, label) => {
    let offset = 0;

    const fail = (message) => {
        assert.fail(`${label}: ${message} at byte offset ${offset}`);
    };

    const skipWhitespace = () => {
        while (
            offset < source.length &&
            (source[offset] === " " ||
                source[offset] === "\t" ||
                source[offset] === "\r" ||
                source[offset] === "\n")
        ) {
            offset += 1;
        }
    };

    const parseString = () => {
        if (source[offset] !== '"') {
            fail("expected a JSON string");
        }
        const start = offset;
        offset += 1;

        while (offset < source.length) {
            const character = source[offset];
            offset += 1;

            if (character === '"') {
                try {
                    return JSON.parse(source.slice(start, offset));
                } catch {
                    fail("invalid JSON string");
                }
            }

            if (character === "\\") {
                if (offset >= source.length) {
                    fail("unterminated JSON escape");
                }
                const escape = source[offset];
                offset += 1;
                if (escape === "u") {
                    const digits = source.slice(offset, offset + 4);
                    if (!/^[0-9a-fA-F]{4}$/.test(digits)) {
                        fail("invalid JSON unicode escape");
                    }
                    offset += 4;
                } else if (!/^["\\/bfnrt]$/.test(escape)) {
                    fail("invalid JSON escape");
                }
            } else if (character.charCodeAt(0) < 0x20) {
                fail("unescaped control character in JSON string");
            }
        }

        fail("unterminated JSON string");
    };

    const parseValue = (jsonPath) => {
        skipWhitespace();
        if (offset >= source.length) {
            fail("expected a JSON value");
        }

        if (source[offset] === "{") {
            offset += 1;
            skipWhitespace();
            const keys = new Set();
            if (source[offset] === "}") {
                offset += 1;
                return;
            }

            while (offset < source.length) {
                skipWhitespace();
                const key = parseString();
                if (keys.has(key)) {
                    fail(`duplicate JSON key ${JSON.stringify(key)} in ${jsonPath}`);
                }
                keys.add(key);
                skipWhitespace();
                if (source[offset] !== ":") {
                    fail("expected ':' after a JSON object key");
                }
                offset += 1;
                parseValue(`${jsonPath}.${key}`);
                skipWhitespace();
                if (source[offset] === "}") {
                    offset += 1;
                    return;
                }
                if (source[offset] !== ",") {
                    fail("expected ',' or '}' in a JSON object");
                }
                offset += 1;
            }
            fail("unterminated JSON object");
        }

        if (source[offset] === "[") {
            offset += 1;
            skipWhitespace();
            if (source[offset] === "]") {
                offset += 1;
                return;
            }

            let index = 0;
            while (offset < source.length) {
                parseValue(`${jsonPath}[${index}]`);
                index += 1;
                skipWhitespace();
                if (source[offset] === "]") {
                    offset += 1;
                    return;
                }
                if (source[offset] !== ",") {
                    fail("expected ',' or ']' in a JSON array");
                }
                offset += 1;
            }
            fail("unterminated JSON array");
        }

        if (source[offset] === '"') {
            parseString();
            return;
        }

        const scalar = source
            .slice(offset)
            .match(/^(?:true|false|null|-?(?:0|[1-9][0-9]*)(?:\.[0-9]+)?(?:[eE][+-]?[0-9]+)?)/);
        if (!scalar) {
            fail("invalid JSON value");
        }
        offset += scalar[0].length;
        if (
            offset < source.length &&
            !/^[\s,\]}]$/.test(source[offset])
        ) {
            fail("invalid character after a JSON scalar");
        }
    };

    parseValue("$");
    skipWhitespace();
    if (offset !== source.length) {
        fail("unexpected trailing JSON content");
    }
};

const readJson = async (file) => {
    const source = await readFile(file, "utf8");
    assertJsonObjectKeysUnique(source, relative(file));
    try {
        return JSON.parse(source);
    } catch (error) {
        assert.fail(`${relative(file)} is not valid JSON: ${error.message}`);
    }
};

const assertPlainObject = (value, label) => {
    assert.ok(
        value !== null && typeof value === "object" && !Array.isArray(value),
        `${label} must be an object`,
    );
};

const readRegularFiles = async (directory, label) => {
    const entries = await readdir(directory, { withFileTypes: true });
    for (const entry of entries) {
        assert.ok(entry.isFile(), `${label} contains non-file entry ${entry.name}`);
    }
    return entries.map((entry) => entry.name).sort();
};

const assertCapability = (capability, expectedIdentifier) => {
    const label = `capability ${expectedIdentifier}`;
    assertPlainObject(capability, label);
    assert.deepEqual(
        Object.keys(capability).sort(),
        ["description", "identifier", "local", "permissions", "windows"],
        `${label} contains missing or unsupported top-level fields`,
    );
    assert.equal(capability.identifier, expectedIdentifier);
    assert.equal(typeof capability.description, "string");
    assert.ok(capability.description.length > 0);
    assert.equal(capability.local, true);
    assert.deepEqual(capability.windows, ["main"]);
    assert.ok(Array.isArray(capability.permissions));
    assert.ok(capability.permissions.length > 0);
    assertUnique(capability.permissions, `${label} permissions`);

    return capability.permissions.map((permission) =>
        commandForPermission(permission, `${label} permissions`),
    );
};

const assertCapabilitySelection = (config, expected, label) => {
    assertPlainObject(config, label);
    assertPlainObject(config.app, `${label}.app`);
    assertPlainObject(config.app.security, `${label}.app.security`);
    const capabilities = config.app.security.capabilities;
    assert.ok(Array.isArray(capabilities), `${label} capabilities must be an array`);
    assertUnique(capabilities, `${label} capabilities`);
    assert.deepEqual(capabilities, expected, `${label} selects an unexpected capability`);
};

const expectedPermissionToml = (command) => {
    const permission = permissionForCommand(command);
    return `# Automatically generated - DO NOT EDIT!

[[permission]]
identifier = "${permission}"
description = "Enables the ${command} command without any pre-configured scope."
commands.allow = ["${command}"]

[[permission]]
identifier = "deny-${permission.slice("allow-".length)}"
description = "Denies the ${command} command without any pre-configured scope."
commands.deny = ["${command}"]
`;
};

const parseGeneratedPermissionToml = (source, label) => {
    const normalized = source.replaceAll("\r\n", "\n");
    assert.equal(normalized.includes("\r"), false, `${label} contains a bare carriage return`);
    const allowEntries = [
        ...normalized.matchAll(/^commands\.allow = \["([^"]+)"\]$/gm),
    ];
    assert.equal(allowEntries.length, 1, `${label} must contain exactly one commands.allow entry`);
    const command = allowEntries[0][1];
    assert.match(command, commandPattern, `${label} contains a malformed allow command`);
    assert.equal(
        normalized,
        expectedPermissionToml(command),
        `${label} does not match the canonical autogenerated permission structure`,
    );
    return {
        command,
        identifier: permissionForCommand(command),
    };
};

const runSelfTest = () => {
    assert.deepEqual(
        parseGeneratedPermissionToml(
            expectedPermissionToml("dispose_chat_stream"),
            "valid permission fixture",
        ),
        {
            command: "dispose_chat_stream",
            identifier: "allow-dispose-chat-stream",
        },
    );
    assertJsonObjectKeysUnique(
        '{"outer":{"first":1,"second":[true,false,null]},"other":"value"}',
        "valid JSON fixture",
    );

    assert.throws(() =>
        parseStrictList('"same_command", "same_command",', /^"([^"]+)"\s*,/, "duplicate fixture"),
    );
    assert.throws(() =>
        parseStrictList(
            "commands::valid_command, unsupported!(other),",
            /^(?:[A-Za-z_][A-Za-z0-9_]*::)+([a-z][a-z0-9]*(?:_[a-z0-9]+)*)\s*,/,
            "malformed handler fixture",
        ),
    );
    assert.throws(() =>
        parseFrontendCommandRegistry(
            "export const LOREPIA_COMMANDS = { wrongKey: 'valid_command', } as const;",
        ),
    );
    assert.throws(() =>
        assertJsonObjectKeysUnique('{"duplicate":1,"duplicate":2}', "duplicate JSON fixture"),
    );
    assert.throws(() =>
        parseGeneratedPermissionToml(
            expectedPermissionToml("dispose_chat_stream").replace(
                'commands.allow = ["dispose_chat_stream"]',
                'commands.allow = ["other_command"]',
            ),
            "mismatched permission fixture",
        ),
    );

    console.log("Tauri capability checker self-test passed.");
};

const checkRepository = async () => {
    const capabilityFiles = await readRegularFiles(capabilityRoot, "capability directory");
    assert.deepEqual(capabilityFiles, [
        "main-development.json",
        "main-release.json",
    ]);

    const development = await readJson(
        path.join(capabilityRoot, "main-development.json"),
    );
    const release = await readJson(path.join(capabilityRoot, "main-release.json"));
    const baseConfig = await readJson(path.join(tauriRoot, "tauri.conf.json"));
    const developmentConfig = await readJson(
        path.join(tauriRoot, "tauri.dev.conf.json"),
    );
    const releaseConfig = await readJson(
        path.join(tauriRoot, "tauri.release.conf.json"),
    );

    assertCapabilitySelection(baseConfig, [], "base Tauri config");
    assertCapabilitySelection(
        developmentConfig,
        ["main-development"],
        "development Tauri config",
    );
    assertCapabilitySelection(
        releaseConfig,
        ["main-release"],
        "release Tauri config",
    );

    const developmentCommands = assertCapability(development, "main-development");
    const releaseCommands = assertCapability(release, "main-release");
    assert.deepEqual(
        development.permissions,
        release.permissions,
        "development and release command allowlists must remain identical",
    );

    const handlerSource = await readFile(
        path.join(tauriRoot, "src", "lib.rs"),
        "utf8",
    );
    const handlerCommands = parseInvokeHandler(handlerSource);

    const buildSource = await readFile(path.join(tauriRoot, "build.rs"), "utf8");
    const buildCommands = parseBuildCommands(buildSource);

    const frontendSource = await readFile(
        path.join(appRoot, "src", "lib", "ipc", "client.ts"),
        "utf8",
    );
    const frontendCommands = parseFrontendCommandRegistry(frontendSource);

    const permissionFiles = await readRegularFiles(
        permissionRoot,
        "autogenerated permission directory",
    );
    for (const file of permissionFiles) {
        assert.match(
            file,
            /^[a-z][a-z0-9]*(?:_[a-z0-9]+)*\.toml$/,
            `autogenerated permission directory contains malformed filename ${file}`,
        );
    }
    const permissionRecords = await Promise.all(
        permissionFiles.map(async (file) => {
            const fullPath = path.join(permissionRoot, file);
            const record = parseGeneratedPermissionToml(
                await readFile(fullPath, "utf8"),
                relative(fullPath),
            );
            assert.equal(
                file,
                `${record.command}.toml`,
                `${relative(fullPath)} filename does not match its allow command`,
            );
            return record;
        }),
    );
    const generatedCommands = permissionRecords.map(({ command }) => command);
    const generatedIdentifiers = permissionRecords.map(({ identifier }) => identifier);
    assertUnique(generatedCommands, "autogenerated permission commands");
    assertUnique(generatedIdentifiers, "autogenerated permission identifiers");

    for (const [label, commands] of [
        ["build.rs APP_COMMANDS", buildCommands],
        ["development capability permissions", developmentCommands],
        ["release capability permissions", releaseCommands],
        ["frontend LOREPIA_COMMANDS values", frontendCommands],
        ["autogenerated permission TOMLs", generatedCommands],
    ]) {
        assertExactCommandSurface(handlerCommands, commands, label);
    }

    assert.deepEqual(
        generatedIdentifiers.sort(),
        handlerCommands.map(permissionForCommand).sort(),
        "autogenerated permission identifiers drifted from the Tauri invoke handler",
    );

    console.log(
        `Verified ${handlerCommands.length} explicit Tauri commands across the invoke handler, build manifest, development/release capabilities, frontend registry, and autogenerated permission TOMLs.`,
    );
};

const arguments_ = process.argv.slice(2);
if (arguments_.length === 1 && arguments_[0] === "--self-test") {
    runSelfTest();
} else {
    assert.deepEqual(
        arguments_,
        [],
        "usage: check-tauri-capabilities.mjs [--self-test]",
    );
    await checkRepository();
}
